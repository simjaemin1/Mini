function renameFile(f) {
  if (!fs.existsSync(f)) return null;
  const t = JSON.parse(fs.readFileSync(f, 'utf8'));
  let n = 0; const hits = {};
  const ren = (s) => {
    const m = String(s).match(/^(.+?)(_\d+)?$/);
    const base = m[1], suf = m[2] || '';
    if (MAP[base]) { hits[base] = (hits[base] || 0) + 1; n++; return MAP[base] + suf; }
    return s;
  };
  const walk = (o) => {
    if (Array.isArray(o)) { o.forEach(walk); return; }
    if (o && typeof o === 'object') for (const k of Object.keys(o)) {
      if ((k === 'name' || k === 'procName') && typeof o[k] === 'string') o[k] = ren(o[k]);
      else walk(o[k]);
    }
  };
  walk(t);
  fs.writeFileSync(f, JSON.stringify(t));
  return { n, kinds: Object.keys(hits).length };
}

