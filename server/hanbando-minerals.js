// ★[재민 확정] "지역은 무관해야 해 … 자원도 골고루 섞이게 해줘"
//
// ── 폐기된 안: 실제 산지 지도 ──────────────────────────────────────────────
//   한때 실제 한반도 광물 분포(함북 철·평북 금·평남 석탄·상동 텅스텐·춘천 옥 …)를
//   좌표 띠에 입혔었다. 고증은 맞았지만 **재민이 기각**했다 — 지형이 실존 지명을 쓰지 않는
//   가상 세계인데 광물만 실제 지리를 따르면 어긋난다. 그리고 지역 전문화가 강해지면
//   "이 광물은 저 끝까지 가야 난다"가 되어 어느 마을은 영영 특정 광종을 못 만진다.
//   ⇒ 지역 편중을 **완전히 없앤다**. 어디서든 여덟 광종이 다 나올 수 있다.
//
// ── 지금 규칙: 전역 가중 추첨 ──────────────────────────────────────────────
//   광종은 좌표 해시 하나로 정한다. 위치는 **아무 영향이 없다**(띠도, 중심도, 거리도 없음).
//   ⇒ 어느 구역을 떼어 봐도 여덟 광종의 비율이 같다. 마을마다 광종 운이 갈리지 않는다.
//
//   가중치는 "골고루"를 뜻대로 옮긴 값이다 — 철만 조금 높고 나머지는 사실상 동률:
//     철 18 · 석탄 14 · 구리 13 · 대리석 13 · 옥 13 · 텅스텐 13 · 금 13 · 주석 1.2
//
//   ★주석만 낮은 이유: 재민이 앞서 정한 **구리:주석 ≈ 1:12** 를 지키기 위해서다.
//     (주석은 가치 4라 품위배율이 1.0 = 구리와 같다. 가중치를 같이 주면 구리만큼 나와
//      청동이 흔해진다. 주석이 귀한 건 청동기라는 시대 설정의 뼈대다.)
//     이건 **지역 편중이 아니라 총량 조절**이다 — 주석도 지도 전역에 고르게 흩어진다.
//
//   ※품위(p_peak)는 여기서 안 정한다. 그건 로그정규 뽑기 × 가치배율의 몫이다(specialty.js).
//     광종 해시는 씨앗 731, 품위 지터는 500 — 분리해야 광종과 품위가 상관되지 않는다.

// ★[재민 확정] **텅스텐 제거.** 두 가지 이유가 겹친다:
//   · 고증 — 텅스텐(중석)은 융점 3422℃로 청동기 기술로는 제련이 불가능하다. 이 시대에 존재할 수 없다.
//   · 코드 — econ 전체에 참조 0건. 캐도 쓸 데가 없어 영원히 쌓이기만 했다(감사_금속수급_실측.md).
//   빠진 가중치는 나머지에 비례 배분한다(총량 중립은 ORE_P_SCALE 로 따로 맞춘다).
const POOL = {
  iron: 21,        // 철광석
  coal: 16,        // 석탄     ※싱크 0 — 회부 중(청동기 제련 연료는 목탄이지 석탄이 아니다)
  copper: 15,      // 구리
  marble: 15,      // 대리석   ※싱크 0 — 회부 중(한반도 산지는 실재하나 청동기 유물 재료 근거 없음)
  jade_raw: 15,    // 옥 원석
  gold: 15,        // 금
  tin: 1.4,        // 주석 — 구리:주석 ≈ 1:11 (지역 편중이 아니라 총량 조절)
};

function _pick(pool, u) {
  let s = 0; for (const k in pool) s += pool[k];
  let r = Math.max(0, Math.min(1 - 1e-12, u)) * s;
  for (const k in pool) { r -= pool[k]; if (r < 0) return k; }
  return Object.keys(pool)[0];
}

// 좌표는 받지만 **쓰지 않는다** — 호출부 호환용이자, 지역 무관을 코드로 못 박는 자리다.
// (여기에 cx·cy 를 다시 끌어들이면 지역 편중이 되살아난다. 하네스가 그걸 검사한다.)
function mineralAt(cx, cy, u) { return _pick(POOL, u); }

// ── NPC 시야 광맥의 **광종 최소 보장** ────────────────────────────────────
//   NPC·마을 경제는 자잘 광맥을 못 본다(isMajorOreAt). 그런데 대·중·소는 2671개 중 63개뿐이라
//   가중치가 낮은 광종은 **한 개도 안 걸릴 수 있다**. 실측으로 그랬다 — 주석 26개가 전부 자잘로
//   떨어져 **마을 경제의 주석이 0** 이 됐다. 청동기 게임에서 마을이 청동을 못 만든다는 뜻이다.
//   ⇒ 대·중·소에 한해 여덟 광종이 **최소 MIN_MAJOR 개씩** 들어가도록 보정한다.
//     · 지역과 무관하다(어느 광맥을 바꿀지는 좌표가 아니라 **해시 순서**로 정한다)
//     · 넘치는 광종(가장 많이 배정된 것)에서 뺏어 온다 — 총 개수는 그대로다
//     · 결정론: 같은 입력이면 같은 결과다
const MIN_MAJOR = 2;
function balanceMajors(majors, hashOf) {
  const idx = majors.map((o, i) => ({ o, h: hashOf(o, i) })).sort((a, b) => a.h - b.h);
  const count = () => { const c = {}; for (const k in POOL) c[k] = 0; for (const e of idx) c[e.o.mineral] = (c[e.o.mineral] || 0) + 1; return c; };
  for (const need of Object.keys(POOL)) {
    let c = count();
    while (c[need] < MIN_MAJOR) {
      // 가장 많은 광종에서 하나 뺏는다(동률이면 이름 순 — 결정론)
      let rich = null;
      for (const k of Object.keys(POOL)) if (k !== need && (rich === null || c[k] > c[rich] || (c[k] === c[rich] && k < rich))) rich = k;
      if (rich === null || c[rich] <= MIN_MAJOR) break;
      const victim = idx.find((e) => e.o.mineral === rich);
      if (!victim) break;
      victim.o.mineral = need;
      c = count();
    }
  }
  return majors;
}

module.exports = { POOL, mineralAt, balanceMajors, MIN_MAJOR };
