//   이 게임의 첫 캐논은 **주사위 금지**(07-12 · 재민)다. 그런데 T340 이 걸음 하나를 세어 보니
//   `decideNpcBehavior` 가 **걸음마다 `Math.random` 을 15번** 굴리고 있었다. T345 는 그 값을 치르고
//   알았다 — 재작성의 게이트("같은 씨 같은 좌표")가 **성립하지 않는다**. 두 판이 같은 틱에 같은 결정을
//   안 하므로 좌표가 달라도 재작성 탓인지 주사위 탓인지 **못 가른다**. ⇒ 주사위를 먼저 없앤다.
//
// ★여기 있는 셋은 전부 **이미 이 레포에 있던 것**이다(사본 0 · 새 수 0). 옮겨 모았을 뿐이다:
//   ⓐ `step`/`out` — T340 `villages.js:_t340Rng` 의 그 두 줄. 상수 둘도 그 자리의 것이다
//      (`0x85ebca6b` T312 · `0x9e3779b9` T297 — 지어낸 수 0).
//   ⓑ `pidHash`   — `villages.js:_pidHash`(신원 해시 · `h*31+c`). 벌수 줄 세우기가 쓰던 그 함수다.
//   ⓒ `seedOf`    — T340 이 `_t340Try` 에서 쓴 섞는 꼴(`h ^ imul(n,A) ^ imul(day,B)`)을 다섯 항으로 편 것.
//      항 사이에 `step` 을 한 번씩 돌린다 — 안 그러면 같은 상수를 두 항이 나눠 써 **서로 지운다**
//      (cx 와 day 가 같으면 XOR 이 0 이 된다). 섞는 재료는 `step` 하나뿐이다.
//
// ★두 꼴을 낸다 — **쓰임이 둘이라서**다(구현은 하나다):
//   · `seedRand(seed)` — 닫힌 흐름 하나(호출마다 새 함수). T340 이 쓰던 그 꼴 · `plan(…, rng)` 처럼
//     **rng 를 인수로 받는 자리**에 넘긴다.
//   · `makeStream()`   — 흐름 하나를 **다시 씨 뿌려 가며** 쓴다(`seed(v)` → `next()`). 틱마다 영점을
//     잡는 자리(몹·야생)가 쓴다. 할당 0 이다 — 걸음 문 안에서 호출마다 클로저를 만들면 안 된다(T345).
//
// ★분포는 안 바뀐다. `out` 은 24비트 균등([0,1))이고 `Math.random` 과 같은 모양이다 —
//   `test-move-soa ⑤` 가 10만 굴림 히스토그램을 **T252 자**(3시드 부호 3/3 + |평균| > 폭)로 견준다.
'use strict';

// ── ⓐ 한 스텝 — 모든 것이 이 한 줄에서 난다(사본 0) ────────────────────────────
const step = (s) => (Math.imul(s ^ (s >>> 15), 0x85ebca6b) + 0x9e3779b9) >>> 0;
const out = (s) => ((s >>> 8) / 16777216) || 1e-9;

// ── ⓑ 신원 해시 — `villages.js:_pidHash` 그대로(문자열 pid → 32비트) ──────────
function pidHash(pid) { let h = 7; const s2 = String(pid); for (let i = 0; i < s2.length; i++) h = (h * 31 + s2.charCodeAt(i)) >>> 0; return h; }

// ── ⓒ 씨 짓기 — (신원 · 셀 · 게임일 · 틱) ─────────────────────────────────────
//   ⚠`pidH` 는 **이미 해시된 수**를 받는다(문자열을 걸음마다 다시 해시하면 그게 곧 T345 가 지운 쓰레기다 —
//     부르는 쪽이 `npc._sh` 에 한 번 굽고 그걸 넘긴다).
function seedOf(pidH, cx, cy, day, tick) {
  let s = (pidH >>> 0) || 1;
  s = step(s ^ Math.imul(cx | 0, 0x9e3779b9));
  s = step(s ^ Math.imul(cy | 0, 0x85ebca6b));
  s = step(s ^ Math.imul(day | 0, 0x9e3779b9));
  s = step(s ^ Math.imul(tick | 0, 0x85ebca6b));
  // ★마무리 한 바퀴 — 입력이 **격자**(pid 가 연번 · 셀이 등차 · 틱이 주기)라 항만 섞고 끝내면
  //   첫 수에 그 격자가 희미하게 남는다. 실측: 첫 굴림 10만 개 χ²(20칸) 평균 24.6 → **20.1**
  //   (이론값 df=19 · `Math.random` 자신의 3표본은 17~34 로 흔들린다). 섞는 재료는 여전히 `step` 하나다.
  return step(s);
}

// ── 꼴 ① 닫힌 흐름(T340 `_t340Rng` 과 **바이트 동일**) ────────────────────────
function seedRand(seed) {
  let s = (seed >>> 0) || 1;
  return () => { s = step(s); return out(s); };
}

// ── 꼴 ② 다시 씨 뿌리는 흐름(할당 0 — 걸음 문·틱 루프용) ──────────────────────
function makeStream() {
  let s = 1;
  return {
    seed(v) { s = (v >>> 0) || 1; },
    next() { s = step(s); return out(s); },
    get state() { return s; },
  };
}

module.exports = { step, out, pidHash, seedOf, seedRand, makeStream };
