// === server/snow.js — 적설: **세계가 겨울을 안다** [T487 2026-09-28] ======================
//
// ★재민 실기 09-28: *"지금 겨울에도 전혀 티가 안 나서 겨울인지 직관적으로 안 느껴진다."*
//   있던 겨울 신호는 달력 배지 · 날씨 배지 한 낱말 · 밤에만 그려지는 눈발이 전부였고
//   **땅에 남는 것이 없었다.** 눈이 와도 다음 프레임이면 없던 일이 된다.
//   ⇒ 이 모듈이 적설을 **세계 상태**로 세운다: 그림이 아니라 값이다(관측자와 무관하다).
//
// ★★새 수 0 — 재료는 전부 **이미 있는 정본**이다(읽기만 · `weather.js` 무수정 · T484 자리 무접촉):
//   `precipAt(day)`  그날의 강수 강도(0..1 · T98 · 앵커 = 기상청 부여 평년 강수일수)
//   `tempAt(day, night)`  그날 낮/밤 기온(℃ · econ `temperatureAt` + 편차 + 일교차)
//   그리고 **물의 상변화 0℃** — 세계 규칙이 아니라 물리다(T93 이 눈/비를 가른 그 문턱).
//
// ── ★유도식 표 (카드 ① "계수는 0℃·하루 1 눈금에서 유도") ──────────────────────────
//   │ 항            │ 값                          │ 어디서 왔나                                  │
//   │ 문턱 T₀       │ 0℃                          │ 물의 어는점(물리) · 37-r1-weather 눈/비 문턱   │
//   │ 한 걸음 Δt    │ 1 게임일                    │ 카드 "하루 한 번" · 존 게임일 경계(결산 문)     │
//   │ 눈금          │ snow 0..1 (1 = 땅이 다 덮임) │ 카드 "상한 1" — 강수 강도와 **같은 눈금**       │
//   │ 쌓임(d)       │ precipAt(d)                 │ 그날 밤 기온 < T₀ 일 때만 · 강도 **그대로**      │
//   │ 녹음 계수 k   │ 1 눈금 / (1℃ · 1일)          │ 단위 셋이 전부 1 — "0℃ 위 1℃ 로 하루면 한 눈금" │
//   │ 녹음(d)       │ k · max(0, T낮(d) − T₀) · Δt │ ℃ 비례(도일법 degree-day 의 꼴)               │
//   ⇒ 계수 k 는 **고른 수가 아니다**: 눈금·℃·일이 각각 제 단위 1 일 때의 값이라 곱하면 1 이다.
//     (실세계의 도일 계수를 들이면 그게 새 수다 — 이 카드는 그 길을 안 간다.)
//
// ── ★순서 — 게임일 하나 안에서 **낮이 먼저, 밤이 나중**이다 ─────────────────────────
//   `zone-config.isNight` = 위상 0.7 초과(`dayPhaseRatio`) ⇒ 하루 = 낮(0~0.7) 다음 밤(0.7~1).
//   ⇒ 날 d 의 결산(d → d+1 경계)은 ⓐ 그날 낮이 녹이고 ⓑ 그날 밤이 쌓는다:
//        S(d+1) = min(1, max(0, S(d) − 녹음(d)) + 쌓임(d))        S(0) = 0 (세계가 난 날 · 봄 첫날)
//   S(d) 는 **날 d 내내 보이는 값**이다(하루 한 번 바뀐다). 눈 온 밤의 다음 아침이 하얗고,
//   그날 낮 기온이 영상이면 다음 결산에서 녹는다.
//
// ── ★결정론 · 관측자 무관 ───────────────────────────────────────────────────────
//   재료가 전부 **절대 게임일의 순수 함수**라 S(d) 도 d 의 순수 함수다(씨앗이 같으면 어느 존·어느 재시작이든 같다).
//   ⇒ 저장할 것이 없다: 존이 날 D 에 처음 물으면 0 일부터 재생하고(수천 걸음 · ms 단위),
//     그 뒤로는 하루에 **한 걸음**씩 민다(메모). 재생과 한 걸음씩 민 값은 **같은 식 같은 순서**라 비트까지 같다.
//   ⚠날짜가 뒤로 가면(하네스 시계) 0 일부터 다시 재생한다 — 느려질 뿐 답은 같다.
//
// ★이 파일에 **손잡이가 없다.** 켜고 끄는 것은 `zone.js` 의 `T487_SNOW` 하나다(카드 "손잡이 하나").
//
// ── ★★[T500 2026-09-28] 서리 — "밤 tempC < 0 ∧ snow = 0 인 아침 지면 흰 기미 · 첫 낮에 사라짐" ──
//   재료는 위 적설과 **같은 셋**이다(두 기온 · 어는점 T₀ · 녹음 계수 k = 1) — 새 수 0 · 새 문턱 0(0℃ 하나).
//   │ 항            │ 값                                        │ 어디서 왔나                                 │
//   │ 맺힘 조건      │ T밤(d) < T₀ ∧ S(d+1) = 0                  │ 카드 "밤 tempC < 0 ∧ snow = 0 인 아침"        │
//   │ 양 F₀(d)      │ (T₀ − T밤(d)) / (T낮(d) − T밤(d))  · 0..1  │ 그날 일교차 가운데 **어는점 아래 몫** — 기온 둘 · T₀ 뿐 │
//   │ 눈금          │ 적설과 같은 0..1                           │ 카드 "적설 색의 낮은 값" — 같은 칠(ICE_COLOR)의 알파 │
//   │ 녹음          │ k · max(0, T낮(d+1) − T₀) · (아침부터 흐른 날) │ 위 적설 녹음과 **같은 식 같은 k**              │
//   │ 사라짐        │ 녹은 양 ≥ F₀ 인 순간 0 (그 전까지 F₀ 그대로)  │ 이진 — 값이 바뀔 때마다 땅을 다시 굽지 않는다(판 1장) │
//   ⇒ F₀ 는 밤이 어는점에 **겨우** 닿으면 0 에 가깝고, 하루 전체가 어는점 아래면 1 이다(그때는 서리가 아니라 온 땅이 언 것이다).
//     4씨앗 × 세 해 실측(`test-winter-fx ③` · T500 보고): 언 밤의 67~79% 가 서리 밤 · F₀ 평균 0.29~0.42 · 해 뜨고 평균 0.045~0.11 일(실시간 1.1~2.7 분)에 녹는다.
//   ⚠순서는 적설과 같다 — 날 d = 낮(0~0.7) 다음 밤(0.7~1). 밤 d 에 맺힌 서리가 **날 d+1 아침**에 보이고 그 낮에 녹는다.
//   ⚠밤에 보이는 땅은 S(d)(그날 낮의 적설) 이므로, 그 값이 0 이 아닌 밤엔 서리를 안 얹는다(눈 위에 서리를 두 번 칠하지 않는다).
'use strict';

/**
 * 날씨 모듈 하나에 묶인 적설 계산기를 만든다.
 *   제품: `module.exports` 가 정본 `./weather` 에 묶인 하나를 낸다.
 *   하네스: 씨앗을 갈아 끼운 **새 사본**(`test-weather` `loadWeather` 문법)을 넣어 3시드를 잰다.
 */
function make(W) {
  const T0 = 0;                                     // ℃ — 물의 어는점(물리 · 위 표)
  /** 그날 밤에 쌓이는 몫 — 강수가 있고 **밤 기온이 어는점 아래**면 강도 그대로. */
  function accOf(day) {
    const p = W.precipAt(day);
    if (!(p > 0)) return 0;
    const tN = W.tempAt(day, true, 0);
    if (tN === null || tN === undefined) return 0;    // econ 정본을 못 물면 거짓말을 지어내지 않는다
    return tN < T0 ? p : 0;
  }
  /** 그날 낮에 녹는 몫 — k·max(0, T낮 − T₀)·Δt, k = Δt = 1(위 표). */
  function meltOf(day) {
    const tD = W.tempAt(day, false, 0);
    if (tD === null || tD === undefined) return 0;
    return Math.max(0, tD - T0);
  }
  /** 결산 한 걸음 — 날 d 의 값 `prev` → 날 d+1 의 값. 낮이 먼저 녹이고 밤이 쌓는다. */
  function stepOf(prev, day) {
    return Math.min(1, Math.max(0, prev - meltOf(day)) + accOf(day));
  }
  // ── 메모 — 존 하나에 값 하나(마지막으로 물은 날과 그 값) ──
  let _d = 0, _v = 0;                                // S(0) = 0
  /** 날 `day` 내내 보이는 적설(0..1 · 날것). 하루에 한 걸음씩 민다. */
  function at(day) {
    const d = Math.max(0, day | 0);
    if (d < _d) { _d = 0; _v = 0; }                  // 뒤로 가면 처음부터(답은 같다 · 느려질 뿐)
    while (_d < d) { _v = stepOf(_v, _d); _d++; }
    return _v;
  }
  /** 화면·스냅에 싣는 값 — 넷째 자리까지(다른 날씨 칸과 같은 문법 · `precip` 도 `toFixed(4)`). */
  function snowAt(day) { return +at(day).toFixed(4); }
  /** 하네스용 — 0 일부터 **메모 없이** 재생한 값(메모가 답을 바꾸지 않는가를 잰다). */
  function replay(day) {
    let v = 0;
    for (let d = 0; d < Math.max(0, day | 0); d++) v = stepOf(v, d);
    return v;
  }
  // ── ★[T500] 서리 — 위 머리 표. 메모는 **앞으로만** 민다(`at(d+1)` 대신 `stepOf(at(d), d)` — 뒤로 가면 0 일부터 재생이다) ──
  /** 밤 `dn` 의 서리 양 — 다음 아침 적설 `sMorning` 이 0 이고 그 밤이 얼었을 때만. */
  function _frostFormed(dn, sMorning) {
    if (sMorning !== 0) return 0;                     // 다음 아침에 눈이 덮였으면 서리가 아니라 눈이다
    const tN = W.tempAt(dn, true, 0), tD = W.tempAt(dn, false, 0);
    if (tN === null || tN === undefined || tD === null || tD === undefined) return 0;
    if (!(tN < T0)) return 0;
    const span = tD - tN;
    return span > 0 ? Math.min(1, (T0 - tN) / span) : 1;   // 일교차가 없으면(한 번도 녹을 틈이 없으면) 다 언 것이다
  }
  /** 밤 `day` 에 맺히는 서리 F₀(0..1 · 날것) — 곡선 표·하네스용. */
  function frostOf(day) {
    const d = Math.max(0, day | 0);
    return _frostFormed(d, stepOf(at(d), d));
  }
  /**
   * 지금 땅에 보이는 서리(0..1 · 넷째 자리) — 날 `day` · 밤인가 `night` · 그날 위상 `phase`(낮이면 아침부터 흐른 날).
   *   밤 d  : S(d) = 0 이면 F₀(d)(맺히는 중) · 아니면 0
   *   낮 d  : F₀(d−1)(지난밤 것) — k·max(0, T낮(d))·phase ≥ F₀ 가 되는 순간 0(첫 낮에 사라짐)
   */
  function frostAt(day, night, phase) {
    const d = Math.max(0, day | 0);
    const s = at(d);
    let f;
    if (night) f = (s === 0) ? _frostFormed(d, stepOf(s, d)) : 0;
    else {
      if (d === 0) return 0;                          // 세계가 난 날 아침 — 지난밤이 없다
      f = _frostFormed(d - 1, s);                     // S(d) = 지난밤 d−1 다음 아침의 적설(메모를 뒤로 안 민다)
      if (f > 0 && meltOf(d) * Math.max(0, +phase || 0) >= f) f = 0;
    }
    return +f.toFixed(4);
  }
  return { T0, accOf, meltOf, stepOf, at, snowAt, replay, frostOf, frostAt, memo: () => ({ day: _d, v: _v }) };
}

module.exports = Object.assign(make(require('./weather')), { make });
