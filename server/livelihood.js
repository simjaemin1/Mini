// === server/livelihood.js — 생업별 부존(토지값) **정본** ===
//
// ★[11차 재민 확정] "농사만으로 보면 지역별 차이가 있으면 좋지만, 모든 분야에 대해서도 차이가 심하면
//   안 돼. 어딘가는 반드시 무언가로 먹고살 수 있는 게 있어야 해."
//   → ①종류마다 바닥항 ②광업·사냥을 각자 제 지도로 분리.
//
// 고치기 전 실측(존 전역 2,161자리 격자 · 51마을 전수):
//   wood  중앙 0.25 = **바닥값 그대로**   (0.25 + 숲비율×2.8 인데 절반이 반경 140셀 안에 숲 0)
//   game  중앙 0.20 = **바닥값 그대로**   (wood와 **같은 수식** — 사냥에 독립 지도가 없었다)
//   ore   중앙 0.08 = **바닥값 그대로**   (0.08 + 바위밀도×12 — stone과 같은 수식,
//                                        **광맥(ores) 레이어를 아예 안 봤다**. 광맥까지 실제 중앙값 482셀)
//   stone 중앙 0.10 = 바닥값 그대로
//   → 51마을 중 29곳이 '주의'(생업 4종 이상이 바닥), 6곳은 전부 바닥.
//     그 마을들이 굶지 않은 유일한 이유는 채집 landBoost 바닥 0.3 하나였다.
//
// 그래서 두 가지를 한다:
//   ① **바닥을 살 수 있는 높이로**. 초지에도 덤불·관목이 있고(wood), 사슴·멧돼지가 살고(game),
//      돌은 어디나 나온다(stone). 바닥이 0에 가까우면 '지역차'가 아니라 '못 사는 땅'이 된다.
//   ② **광업은 광맥, 사냥은 사냥터**. 산 옆이라고 광부가 나오면 안 되고(광맥이 있어야 한다),
//      사냥터는 랩과 같이 **마을 밖 40~130셀 밴드**다(마을 안엔 짐승이 안 산다 — 고증).
//
// econ 엔진은 건드리지 않는다. 엔진이 이미 읽는 land.* 값만 바꾼다.
'use strict';

// ---- 바닥값(어디서나 이만큼은 된다) ----
const FLOOR = {
  wood:  0.45,   // 초지의 덤불·관목·유목 — 땔감과 막대는 어디서나 난다
  game:  0.45,   // 초지 사냥(사슴·멧돼지) — 숲이 없어도 짐승은 산다
  stone: 0.25,   // 돌은 흔하다(랩 주석 "돌은 흔하니 누구나 조달")
  ore:   0.10,   // 사철·표사 정도 — 광맥 없이 광부로 먹고살진 못한다
};
// ---- 지형이 얹는 몫 ----
const GAIN = {
  wood:  2.30,   // 숲비율(반경 140셀) — 만림이면 0.45+2.30 = 2.75 → 상한 2.5
  game:  1.80,   // 사냥밴드 숲비율(40~130셀)
  stone: 9.00,   // 바위비율(반경 140셀)
  ore:   2.40,   // ★[11차] **√(광맥 셀비율)** — 계수의 의미가 바뀌었다(아래 ORE_SQRT 참조)
  //   구 60(선형)의 사연: 광맥 8개가 존의 0.125%뿐이고 반지름이 ~21셀이라, 광맥 한복판에 앉은
  //   마을도 반경 140셀 원판의 2.5%밖에 못 채웠다. 그래서 계수를 60까지 올려야 갈라졌다.
  //   ★그런데 광맥을 대·중·소로 키우면 그 선형이 무너진다 — 실측 환산:
  //     대형(r130) 위 마을 원판의 85%가 광맥 → 0.10+60×0.85 = 51 → 캡 2.5
  //     소형(r32)  위 마을 5.2%           → 0.10+60×0.052 = 3.2 → 캡 2.5
  //     ⇒ **대형이든 소형이든 전부 캡**. 광부 정원(size×ore×0.30)이 똑같아져 등급이 무의미해진다.
  //   그래서 선형을 버리고 √로 간다. 0.10 + 2.40·√share 로 잡으면:
  //     대형 85% → 2.31 · 중형 15% → 1.03 · 소형 5.2% → 0.65 · 자잘 0.25% → 0.22
  //     광부 정원(size 40) = 27명 / 12명 / 7명 / 2명 — **광맥 등급이 마을 규모로 번역된다**.
};
const ORE_SQRT = true;   // ore만 √(share) — 나머지 생업은 선형 유지(숲·사냥·바위는 밀도=면적이라 선형이 맞다)
const CAP = 2.5;

const clamp = (v, lo, hi) => Math.max(lo, Math.min(hi, v));

// 생업별 토지값. 인자는 전부 [0,1] 비율.
//   forShare  = 반경 140셀 숲 비율            (임업)
//   huntShare = 마을 밖 40~130셀 밴드 숲 비율 (사냥 — 랩과 같은 밴드)
//   rockShare = 반경 140셀 바위 비율          (채석)
//   oreShare  = 반경 140셀 광맥 비율          (광업)
function landOf({ forShare, huntShare, rockShare, oreShare }) {
  return {
    wood:  +clamp(FLOOR.wood  + GAIN.wood  * forShare,  0.05, CAP).toFixed(2),
    game:  +clamp(FLOOR.game  + GAIN.game  * huntShare, 0.05, CAP).toFixed(2),
    stone: +clamp(FLOOR.stone + GAIN.stone * rockShare, 0.05, CAP).toFixed(2),
    ore:   +clamp(FLOOR.ore   + GAIN.ore   * (ORE_SQRT ? Math.sqrt(Math.max(0, oreShare)) : oreShare), 0.05, CAP).toFixed(2),
  };
}

module.exports = { landOf, FLOOR, GAIN, CAP };
